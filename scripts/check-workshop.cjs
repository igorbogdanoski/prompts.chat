const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const root = path.join(__dirname, '..', 'docs');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), { runScripts: 'outside-only', url: 'https://workshop.example/' });
const w = dom.window;
w.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
w.HTMLDialogElement.prototype.close = function () { this.open = false; };
Object.defineProperty(w, 'isSecureContext', { value: true });
Object.defineProperty(w.navigator, 'clipboard', { value: { writeText: async () => { throw new Error('permission denied'); } } });
