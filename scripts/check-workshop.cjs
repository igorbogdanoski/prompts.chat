 assert.ok([...d.querySelectorAll('.prompt details')].every(el => el.open));
 w.dispatchEvent(new w.Event('afterprint'));
 assert.equal(search.value, 'zzzz');
 assert.equal(d.querySelectorAll('.prompt').length, 0);
