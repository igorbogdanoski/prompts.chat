 for (const category of ['Техничко образование','Општообразовни предмети','Гимназиско образование']) assert.equal(w.WORKSHOP.prompts.filter(p=>p.category===category).length,8);
 assert.equal(w.WORKSHOP.prompts.filter(p => p.category === 'Медицинско образование').length, 8);
